import {config} from "dotenv";
config({path:".env.local"}); config();
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import solc from "solc";
import {createPublicClient,createWalletClient,http,parseUnits,isAddress} from "viem";
import {privateKeyToAccount} from "viem/accounts";
import {ARC_USDC,arc} from "../lib/server/arc";

const privateKey=process.env.DEPLOYER_PRIVATE_KEY;
const agentKey=process.env.AGENT_PRIVATE_KEY;
if(!privateKey||!/^0x[a-fA-F0-9]{64}$/.test(privateKey))throw new Error("DEPLOYER_PRIVATE_KEY is required (local only)");
if(!agentKey||!/^0x[a-fA-F0-9]{64}$/.test(agentKey))throw new Error("AGENT_PRIVATE_KEY required");
const agent=privateKeyToAccount(agentKey as `0x${string}`);
const owner=privateKeyToAccount(privateKey as `0x${string}`);
const single=parseUnits(process.env.SINGLE_LIMIT_USDC||"200",6);
const auto=parseUnits(process.env.AUTONOMOUS_LIMIT_USDC||"50",6);
const daily=parseUnits(process.env.DAILY_LIMIT_USDC||"400",6);
if(auto<=0n||auto>single||single>daily)throw new Error("Limits must satisfy 0 < autonomous <= single <= daily");
const source=readFileSync(resolve("contracts/QuorailVault.sol"),"utf8");
const result=JSON.parse(solc.compile(JSON.stringify({language:"Solidity",sources:{"QuorailVault.sol":{content:source}},settings:{optimizer:{enabled:true,runs:200},outputSelection:{"*":{"*":["abi","evm.bytecode.object"]}}}})));
if(result.errors?.some((x:{severity:string})=>x.severity==="error"))throw new Error(JSON.stringify(result.errors,null,2));
const artifact=result.contracts["QuorailVault.sol"].QuorailVault;
const client=createPublicClient({chain:arc,transport:http(process.env.ARC_RPC_URL||"https://rpc.testnet.arc.network")});
if((await client.getChainId())!==arc.id)throw new Error("Wrong RPC/chain; expected Arc Testnet");
const wallet=createWalletClient({account:owner,chain:arc,transport:http(process.env.ARC_RPC_URL||"https://rpc.testnet.arc.network")});
console.log("Owner:",owner.address,"Agent:",agent.address,"Network:",arc.name);
console.log("Deploying Quorail Vault on Arc Testnet ...");
const hash=await wallet.deployContract({abi:artifact.abi,bytecode:`0x${artifact.evm.bytecode.object}` as `0x${string}`,args:[ARC_USDC,agent.address,auto,single,daily]});
const receipt=await client.waitForTransactionReceipt({hash});
if(receipt.status!=="success"||!receipt.contractAddress)throw new Error("Deployment reverted");
console.log("Vault address:",receipt.contractAddress);
console.log("Explorer:",`https://testnet.arcscan.app/tx/${hash}`);
console.log("Set VAULT_ADDRESS and NEXT_PUBLIC_VAULT_ADDRESS to",receipt.contractAddress);
console.log("NEXT: Owner MUST allowlist recipient addresses via setRecipient and fund the vault with testnet USDC.");
